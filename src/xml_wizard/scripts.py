"""Generate stand-alone Python and R scripts that apply a project's skip logic.

The scripts read a raw REDCap CSV export, classify every gated item in every
row (shown_answered / shown_missing / skipped / skipped_but_answered /
unknown), optionally fill confirmed implied values, and write a cleaned copy
plus reports. They have no dependencies beyond Python 3.8+ or base R.
"""

from __future__ import annotations

import json
import os
from typing import Any, Dict, List

from . import __version__
from .analysis import Analysis

_HERE = os.path.dirname(os.path.abspath(__file__))


def _read(name: str) -> str:
    with open(os.path.join(_HERE, name), encoding="utf-8") as fh:
        return fh.read()


def _rules(analysis: Analysis) -> List[Dict[str, Any]]:
    out = []
    for fld in analysis.gated_fields:
        if fld.is_form_status or not fld.holds_data:
            continue
        info = analysis.fields[fld.name]
        out.append({
            "field": fld.name, "form": fld.form, "type": fld.field_type, "columns": fld.columns,
            "logic": fld.branching_logic, "python": info.python, "r": info.r,
            "why_manual": (fld.logic_error and "logic could not be parsed")
                          or (", ".join(info.unsupported) if info.unsupported else ""),
        })
    return out


def _structure(analysis: Analysis) -> Dict[str, Any]:
    project = analysis.project
    started: Dict[str, List[str]] = {}
    for ins in project.instruments:
        cols: List[str] = []
        for n in ins.fields:
            f = project.fields.get(n)
            if f and f.holds_data and not f.is_form_status and n != project.record_id_field:
                cols.extend(f.columns)
        started[ins.name] = cols
    return {
        "record_id": project.record_id_field,
        "instrument_columns": started,
        "repeating": [i.name for i in project.instruments if i.repeating],
        "event_forms": {e.unique_name: e.forms for e in project.events} if project.longitudinal else {},
    }


def python_script(analysis: Analysis) -> str:
    rules = _rules(analysis)
    lines = []
    for r in rules:
        fn = f"lambda r: {r['python']}" if r["python"] and not r["why_manual"] else "None"
        lines.append(f"    ({r['field']!r}, {r['form']!r}, {r['type']!r}, {r['columns']!r},\n"
                     f"     {r['logic']!r},\n     {fn}),")
    rules_src = "\n".join(lines)
    structure = json.dumps(_structure(analysis), indent=1)
    title = analysis.project.title
    return _PY_TEMPLATE.format(
        title=title, version=__version__, runtime=_read("runtime.py"),
        rules=rules_src, structure=structure,
    )


def r_script(analysis: Analysis) -> str:
    rules = _rules(analysis)
    items = []
    for r in rules:
        fn = f"function(r) {r['r']}" if r["r"] and not r["why_manual"] else "NULL"
        cols = ", ".join(_rq(c) for c in r["columns"])
        items.append(f"  list(field = {_rq(r['field'])}, form = {_rq(r['form'])}, type = {_rq(r['type'])},\n"
                     f"       columns = c({cols}),\n       logic = {_rq(r['logic'])},\n       fn = {fn})")
    st = _structure(analysis)
    ins_cols = ",\n".join(f"  {_rq(k)} = c({', '.join(_rq(c) for c in v)})" for k, v in st["instrument_columns"].items())
    ev_forms = ",\n".join(f"  {_rq(k)} = c({', '.join(_rq(c) for c in v)})" for k, v in st["event_forms"].items())
    return _R_TEMPLATE.format(
        title=analysis.project.title, version=__version__, runtime=_read("r_runtime.R"),
        rules=",\n".join(items), record_id=_rq(st["record_id"]),
        instrument_columns=ins_cols, repeating=", ".join(_rq(x) for x in st["repeating"]),
        event_forms=ev_forms,
    )


def _rq(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


