"""Write the agent bundle: a folder a coding agent can read to work on the data.

Layout::

    agent_bundle/
      AGENTS.md                 primer read by Codex, Cursor and others
      CLAUDE.md                 one line that imports AGENTS.md for Claude Code
      codebook.json             full machine-readable codebook (+ parsed logic)
      skip_logic.csv            one row per item with branching logic
      implied_values.csv        suggested logical fills; humans set confirmed=TRUE
      cleaning/apply_skip_logic.py
      cleaning/apply_skip_logic.R
"""

from __future__ import annotations

import csv
import json
import os
from typing import Any, Dict, List

from . import __version__
from .analysis import Analysis
from .scripts import python_script, r_script


def write_bundle(analysis: Analysis, codebook: Dict[str, Any], out_dir: str, viewer_name: str = "") -> List[str]:
    os.makedirs(os.path.join(out_dir, "cleaning"), exist_ok=True)
    written = []

    def w(rel: str, text: str) -> None:
        path = os.path.join(out_dir, rel)
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
        written.append(path)

    w("codebook.json", json.dumps(codebook, indent=2, ensure_ascii=False) + "\n")
    w("AGENTS.md", agents_md(analysis, codebook, viewer_name))
    w("CLAUDE.md", "@AGENTS.md\n")
    w(os.path.join("cleaning", "apply_skip_logic.py"), python_script(analysis))
    w(os.path.join("cleaning", "apply_skip_logic.R"), r_script(analysis))

    path = os.path.join(out_dir, "skip_logic.csv")
    with open(path, "w", encoding="utf-8", newline="") as fh:
        wr = csv.writer(fh)
        wr.writerow(["field", "instrument", "type", "label", "logic", "logic_in_words", "depends_on",
                     "auto_evaluable", "problems"])
        for fld in analysis.gated_fields:
            info = analysis.fields[fld.name]
            wr.writerow([fld.name, fld.form, fld.field_type, fld.label, fld.branching_logic, info.logic_text,
                         " ".join(info.parents), "TRUE" if (info.python and not info.unsupported) else "FALSE",
                         " | ".join(f"{i.severity}: {i.message}" for i in analysis.issues_for(fld.name))])
    written.append(path)

    path = os.path.join(out_dir, "implied_values.csv")
    with open(path, "w", encoding="utf-8", newline="") as fh:
        wr = csv.writer(fh)
        wr.writerow(["field", "implied_value", "when_field", "when_value", "confirmed", "rationale"])
        for iv in analysis.implied_values:
            wr.writerow([iv["field"], iv["implied_value"], iv["when_field"], iv["when_value"], "FALSE",
                         iv["rationale"]])
    written.append(path)
    return written


