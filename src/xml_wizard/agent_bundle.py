def _md(s: str) -> str:
    return str(s or "").replace("|", "\\|").replace("\n", " ").strip()


def agents_md(analysis: Analysis, codebook: Dict[str, Any], viewer_name: str = "") -> str:
    p = analysis.project
    cb = codebook["project"]
    out: List[str] = []
    a = out.append
    a(f"# Agent guide: {p.title}\n")
    a(f"Generated by XML Wizard {__version__} from `{p.source_file}` ({p.source_format}) on "
      f"{codebook['generated_at'][:10]}. It describes the survey's items and branching (skip) logic so "
      "you can clean and analyse the data without misreading skipped questions as missing data. "
      "Read this file before touching the data.\n")

    a("## Files in this folder\n")
    a("| File | Contents |\n|---|---|")
    a("| `codebook.json` | Every item: label, type, answer codes, export columns, validation, branching logic "
      "(raw, in words, parsed tree, and Python/R translations), dependents, and problems found. "
      "Schema `xml-wizard/codebook` v" + codebook["schema_version"] + ". |")
    a("| `skip_logic.csv` | One row per item with branching logic. |")
    a("| `implied_values.csv` | Suggested logical fills for skipped items. A person sets `confirmed` to TRUE "
      "to approve a rule. |")
    a("| `cleaning/apply_skip_logic.py` / `.R` | Ready-to-run scripts (no dependencies) that add a skip status "
      "for every gated item, apply confirmed fills, and list problems. |")
    if viewer_name:
        a(f"| `../{viewer_name}` | Interactive tree of the survey for people to review. |")
    a("")

    a("## Ground rules\n")
    rules = [
        "Never overwrite the raw REDCap export. Write cleaned data and derived variables to new files, and keep "
        "every recode in a script so it can be rerun and reviewed.",
        "Values are raw REDCap codes. Use the `choices` in `codebook.json` for labels instead of guessing.",
        "A blank in an item with branching logic is not automatically missing data. Classify it first: "
        "`skipped` (hidden by design, a legitimate skip) versus `shown_missing` (real non-response). "
        "Use `cleaning/apply_skip_logic.py` or `.R`, or the `python`/`r` expressions in `codebook.json`.",
        "Only fill implied values from rows of `implied_values.csv` that a person marked `confirmed = TRUE`. "
        "You may propose new rules, but ask the researcher to confirm them; do not decide them yourself.",
        "Rows flagged `skipped_but_answered` hold answers to questions that should have been hidden. Report them; "
        "do not delete or blank them without the researcher's decision.",
        "Keep participant-level data on this computer. Do not paste rows of data into web services or issue "
        "trackers; share aggregate counts instead.",
    ]
    if any(f.identifier for f in p.fields.values()):
        ids = ", ".join(f"`{f.name}`" for f in p.ordered_fields() if f.identifier)
        rules.append(f"These items are flagged as identifiers (PHI) and must be dropped or masked in any "
                     f"analysis dataset you share: {ids}.")
    for i, r in enumerate(rules, 1):
        a(f"{i}. {r}")
    a("")

    a("## Quick start\n")
    a("```bash\n# REDCap: Data Exports > CSV / Microsoft Excel (raw data), variable names as headers\n"
      "python cleaning/apply_skip_logic.py path/to/export.csv\n"
      "# or\nRscript cleaning/apply_skip_logic.R path/to/export.csv\n```\n")
    a("This writes `<export>_cleaned.csv` with a `<field>__skip` column after every gated item, "
      "`skip_logic_report.csv` (counts per item), `skip_logic_problems.csv` (rows to review) and "
      "`implied_values_log.csv`. Add `--legit-skip-code -7` (Python) to write a code into skipped items "
      "instead of leaving them blank.\n")
    a("Skip status values: " + "; ".join(f"`{k}` = {v.rstrip('.')}" for k, v in codebook["conventions"]["skip_status"].items())
      + "; `instrument_not_started` = the respondent has no data in that instrument, so the item is not assessed.\n")

    a("## Project at a glance\n")
    a(f"- Record ID field: `{p.record_id_field}`")
    a(f"- {cb['counts']['items']} items in {cb['counts']['instruments']} instruments; "
      f"{cb['counts']['items_with_branching_logic']} items have branching logic.")
    if p.longitudinal:
        a(f"- Longitudinal: {len(p.events)} events. Data has one row per record per event "
          "(`redcap_event_name`); repeating instruments add `redcap_repeat_instrument` / `redcap_repeat_instance`.")
        for e in p.events:
            a(f"  - `{e.unique_name}` ({_md(e.label)}): {', '.join(e.forms)}")
    a("- Checkbox items are exported as one 0/1 column per option (`item___code`).\n")
    a("| Instrument | Label | Items | With logic | Repeating |\n|---|---|---|---|---|")
    for ins in p.instruments:
        fields = [p.fields[n] for n in ins.fields if n in p.fields and not p.fields[n].is_form_status]
        a(f"| `{ins.name}` | {_md(ins.label)} | {len(fields)} | {sum(1 for f in fields if f.branching_logic)} | "
          f"{'yes' if ins.repeating else 'no'} |")
    a("")

    a("## Survey map with skip logic\n")
    a("Items are listed in survey order. Indented items are only shown when the condition after the arrow is true. "
      "Format: `variable` (type) label [codes] → condition.\n")
    for ins in p.instruments:
        a(f"### {ins.label} (`{ins.name}`)\n")
        for name in ins.fields:
            fld = p.fields.get(name)
            if fld is None or fld.is_form_status:
                continue
            info = analysis.fields[name]
            if info.tree_parent:
                continue
            _map_line(analysis, name, 0, out)
        a("")

    issues = analysis.issues
    a("## Problems found in the branching logic\n")
    if not issues:
        a("None found.\n")
    else:
        a("Fix these in REDCap (Online Designer) where possible; until then, treat the affected items with care.\n")
        for sev in ("error", "warning", "info"):
            for i in [x for x in issues if x.severity == sev]:
                a(f"- **{sev}** `{i.field}`: {i.message}")
        a("")

    if analysis.audit:
        t = analysis.audit["totals"]
        a("## Data check summary\n")
        a(f"Checked {analysis.audit['n_rows']} rows from the export that was supplied (aggregate counts only):\n")
        a(f"- {t['answered_when_hidden']} answers recorded for items that should have been hidden")
        a(f"- {t['blank_when_shown']} blank answers to items that were shown")
        a(f"- {t['skipped_by_design']} blanks that are legitimate skips")
        a(f"- {t['invalid_codes']} values that are not valid answer codes\n")
        rows = [(n, s) for n, s in analysis.audit["fields"].items()
                if s.get("answered_when_hidden") or s.get("blank_when_shown") or s.get("invalid_codes")]
        if rows:
            a("| Item | Answered while hidden | Shown but blank | Invalid codes |\n|---|---|---|---|")
            for n, s in rows:
                a(f"| `{n}` | {s.get('answered_when_hidden', '')} | {s.get('blank_when_shown', '')} | "
                  f"{s.get('invalid_codes') or ''} |")
            a("")

    a("## Suggested logical fills (need confirmation)\n")
    if analysis.implied_values:
        a("When a gate question rules an item out, the skipped item often has a known answer (for example, never "
          "homeless implies not homeless in the past 6 months). These candidates were generated from the logic "
          "and answer labels. Ask the researcher which to confirm, then set `confirmed` to TRUE in "
          "`implied_values.csv` and rerun the cleaning script.\n")
        a("| Item | Fill with | When | Rationale |\n|---|---|---|---|")
        for iv in analysis.implied_values:
            a(f"| `{iv['field']}` | `{iv['implied_value']}` | `{iv['when_field']}` = `{iv['when_value']}` | "
              f"{_md(iv['rationale'])} |")
        a("")
    else:
        a("No candidates were found automatically. Propose rules to the researcher if the design implies them.\n")

    manual = [f for f in analysis.gated_fields
              if not analysis.fields[f.name].python or analysis.fields[f.name].unsupported]
    if manual:
        a("## Items that need manual handling\n")
        a("The scripts cannot evaluate this logic automatically (status `unknown`). Write the condition by hand:\n")
        for f in manual:
            info = analysis.fields[f.name]
            why = f.logic_error or ", ".join(info.unsupported) or "unsupported expression"
            a(f"- `{f.name}`: `{f.branching_logic}` ({why})")
        a("")

    a("## Starting an analysis\n")
    a("- Build a labelled analysis file from the cleaned export: convert coded items to factors using the "
      "`choices` in `codebook.json`, keep `__skip` columns for denominators, and drop form-status "
      "(`*_complete`) columns.")
    a("- Choose denominators deliberately. For a gated item, report it among those who were asked "
      "(`shown_*`), or among everyone after applying confirmed implied values, and say which.")
    a("- Report item non-response (`shown_missing`) separately from skips in descriptive tables.")
    a("- Multi-select (checkbox) items are several 0/1 variables; summarise each option and decide how to treat "
      "\"none of these\" options.")
    num = [f.name for f in p.ordered_fields() if f.validation in ("integer", "number", "int", "float")
           or f.field_type in ("calc", "slider")]
    cat = [f.name for f in p.ordered_fields() if f.is_categorical and not f.is_form_status]
    if cat:
        a(f"- Categorical items: {', '.join(f'`{n}`' for n in cat)}.")
    if num:
        a(f"- Numeric items: {', '.join(f'`{n}`' for n in num)} (check against validation ranges in "
          "`codebook.json`).")
    a("")
    a("## Example requests a researcher might give you\n")
    a("- \"Run the skip-logic script on `data/export.csv` and summarise the problems by item.\"")
    a("- \"Propose implied-value rules for the housing section and explain each one; don't apply them yet.\"")
    a("- \"Make a labelled analysis dataset and a Table 1 by gender, using the codebook for labels.\"")
    a("- \"Write an R script that recodes legitimately skipped items to -7 and documents every recode.\"")
    a("")
    return "\n".join(out) + "\n"


def _map_line(analysis: Analysis, name: str, depth: int, out: List[str]) -> None:
    p = analysis.project
    fld = p.fields[name]
    info = analysis.fields[name]
    codes = ""
    if fld.choices and fld.field_type not in ("yesno", "truefalse"):
        shown = "; ".join(f"{c}={lab}" for c, lab in fld.choices[:12])
        codes = f" [{shown}{'; …' if len(fld.choices) > 12 else ''}]"
    elif fld.field_type in ("yesno", "truefalse"):
        codes = " [1=Yes; 0=No]" if fld.field_type == "yesno" else " [1=True; 0=False]"
    cond = f" → **if {info.logic_text}**" if fld.branching_logic else ""
    flags = ""
    errs = [i for i in analysis.issues_for(name) if i.severity in ("error", "warning")]
    if errs:
        flags = " ⚠ " + "; ".join(i.code for i in errs)
    if fld.field_type == "calc":
        codes = f" = `{fld.calculation}`"
    out.append(f"{'  ' * depth}- `{name}` ({fld.field_type}) {_md(fld.label)[:140]}{codes}{cond}{flags}")
    for child in info.children:
        _map_line(analysis, child, depth + 1, out)
